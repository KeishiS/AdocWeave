import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";

const root = new URL("../", import.meta.url);
const schema = JSON.parse(readFileSync(new URL("protocol/public-api.json", root), "utf8"));
const corpus = JSON.parse(readFileSync(new URL("fixtures/protocol/request-corpus.json", root), "utf8"));
const names = schema.products.map((field) => field.json);
const rustFields = schema.products.map((field) => field.rust);
const header = "// @generated by tools/generate-protocol.mjs from protocol/public-api.json; DO NOT EDIT.\n";
validateSchema();

const requestFields = schema.request.fields.map(({ json }) => json);
const requestEnums = Object.fromEntries(schema.requestEnums.map((name) => [name, schema.enums[name]]));
const mjs = `${header}export const PROTOCOL_SCHEMA_VERSION = ${schema.schemaVersion};\nexport const WORKER_PROTOCOL_VERSION = ${schema.workerProtocolVersion};\nexport const PACKAGE_VERSION = ${JSON.stringify(schema.packageVersion)};\nexport const PRODUCT_FIELDS = ${JSON.stringify(names)};\nexport const REQUEST_FIELDS = ${JSON.stringify(requestFields)};\nexport const REQUEST_ENUMS = ${JSON.stringify(requestEnums)};\n`;
const dts = `${header}export interface ProductSet {\n${names.map((name) => `  ${name}?: boolean;`).join("\n")}\n}\n\nexport type Severity = ${schema.enums.Severity.map(JSON.stringify).join(" | ")};\n\n${dtoDeclaration("TextRange")}\n\n${dtoDeclaration("Diagnostic")}\n\nexport declare const PROTOCOL_SCHEMA_VERSION: ${schema.schemaVersion};\nexport declare const WORKER_PROTOCOL_VERSION: ${schema.workerProtocolVersion};\nexport declare const PACKAGE_VERSION: ${JSON.stringify(schema.packageVersion)};\nexport declare const PRODUCT_FIELDS: readonly [${names.map(JSON.stringify).join(", ")}];\nexport declare const REQUEST_FIELDS: readonly [${requestFields.map(JSON.stringify).join(", ")}];\nexport declare const REQUEST_ENUMS: ${literalType(requestEnums)};\n`;
const rust = `${header}\npub const PROTOCOL_SCHEMA_VERSION: u16 = ${schema.schemaVersion};\npub const WORKER_PROTOCOL_VERSION: u16 = ${schema.workerProtocolVersion};\n\n#[derive(Clone, Copy, Debug, serde::Deserialize, serde::Serialize, Eq, PartialEq)]\n#[serde(rename_all = "camelCase", deny_unknown_fields)]\npub struct WasmProductSet {\n${rustFields.map((name) => `    pub ${name}: bool,`).join("\n")}\n}\n\nimpl Default for WasmProductSet {\n    fn default() -> Self {\n        let products = adocweave::ProductSet::browser_default();\n        Self {\n${rustFields.map((name) => `            ${name}: products.${name},`).join("\n")}\n        }\n    }\n}\n\nimpl From<WasmProductSet> for adocweave::ProductSet {\n    fn from(value: WasmProductSet) -> Self {\n        Self {\n${rustFields.map((name) => `            ${name}: value.${name},`).join("\n")}\n        }\n    }\n}\n`;
const outputs = [
  [new URL("web-worker/protocol.generated.mjs", root), mjs],
  [new URL("web-worker/protocol.generated.d.mts", root), dts],
  [new URL("crates/adocweave-wasm/src/protocol_generated.rs", root), rust],
];
const check = process.argv.includes("--check");
let stale = false;
for (const [path, content] of outputs) {
  let actual = "";
  try { actual = readFileSync(path, "utf8"); } catch {}
  if (actual === content) continue;
  stale = true;
  if (!check) writeFileSync(path, content);
}
if (check && stale) throw new Error("generated protocol files are stale; run node tools/generate-protocol.mjs");

function validateSchema() {
  if (!Number.isInteger(schema.schemaVersion) || !Number.isInteger(schema.workerProtocolVersion)) {
    throw new Error("protocol versions must be integers");
  }
  if (schema.request.unknownFields !== "reject") throw new Error("request must reject unknown fields");
  const fields = schema.request.fields;
  if (!Array.isArray(fields) || new Set(fields.map(({ json }) => json)).size !== fields.length) {
    throw new Error("request fields must have unique names");
  }
  for (const field of fields) {
    if (!field.json || !field.type || (field.required !== true && !Object.hasOwn(field, "default"))) {
      throw new Error(`request field ${field.json ?? "<unnamed>"} must be required or have a default`);
    }
  }
  for (const [name, setting] of Object.entries(schema.settings)) {
    if (setting.unknownFields !== "reject") throw new Error(`${name} must reject unknown fields`);
    for (const field of setting.fields) {
      if (!Object.hasOwn(field, "default")) throw new Error(`${name}.${field.json} has no default`);
    }
  }
  const covered = corpus.enumCases.map(({ enum: name }) => name).sort();
  const expected = [...schema.requestEnums].sort();
  if (JSON.stringify(covered) !== JSON.stringify(expected)) {
    throw new Error("protocol corpus does not cover every request enum exactly once");
  }
  for (const name of expected) {
    if (!Array.isArray(schema.enums[name]) || schema.enums[name].length === 0) {
      throw new Error(`request enum ${name} is missing`);
    }
  }
  if (corpus.oldVersion === schema.packageVersion) throw new Error("old-version corpus uses the current version");
}

function literalType(value) {
  if (value === null) return "null";
  if (Array.isArray(value)) return `readonly [${value.map(literalType).join(", ")}]`;
  if (typeof value === "object") {
    const fields = Object.entries(value)
      .map(([key, item]) => `readonly ${JSON.stringify(key)}: ${literalType(item)}`)
      .join("; ");
    return `{ ${fields} }`;
  }
  return JSON.stringify(value);
}

function dtoDeclaration(name) {
  const fields = schema.dtos[name]?.fields;
  if (!fields) throw new Error(`missing DTO ${name}`);
  return `export interface ${name} {\n${fields.map((field) => `  ${field.json}: ${field.type};`).join("\n")}\n}`;
}
