import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { generateRustPreprocessInputs } from "./protocol-rust-codegen.mjs";

const root = new URL("../", import.meta.url);
const schema = JSON.parse(readFileSync(new URL("protocol/public-api.json", root), "utf8"));
const corpus = JSON.parse(readFileSync(new URL("fixtures/protocol/request-corpus.json", root), "utf8"));
const runtimeBindings = JSON.parse(
  readFileSync(new URL("fixtures/protocol/runtime-bindings.json", root), "utf8"),
);
const names = schema.products.map((field) => field.json);
const rustFields = schema.products.map((field) => field.rust);
const header = "// @generated by tools/generate-protocol.mjs from protocol/public-api.json; DO NOT EDIT.\n";
validateSchema();

const requestFields = schema.request.fields.map(({ json }) => json);
const requestEnums = Object.fromEntries(schema.requestEnums.map((name) => [name, schema.enums[name]]));
const workerMessageFields = Object.fromEntries(
  Object.entries(schema.workerEnvelopes).flatMap(([direction, contract]) =>
    contract.variants
      ? Object.entries(contract.variants).map(([variant, fields]) => [
          `${direction}.${variant}`,
          [contract.tag, ...fields.map(({ json }) => json)],
        ])
      : [],
  ),
);
const validationSchema = runtimeValidationSchema({
  enums: schema.enums,
  settings: schema.settings,
  definitions: schema.definitions,
  preprocessDefinitions: schema.preprocessDefinitions,
  taggedUnions: schema.taggedUnions,
  dtos: schema.dtos,
  request: schema.request,
  preprocessRequest: schema.preprocessRequest,
  response: schema.response,
  productSet: schema.productSet,
  workerEnvelopes: schema.workerEnvelopes,
});
const mjs = `${header}export const PROTOCOL_SCHEMA_VERSION = ${schema.schemaVersion};\nexport const WORKER_PROTOCOL_VERSION = ${schema.workerProtocolVersion};\nexport const PACKAGE_VERSION = ${JSON.stringify(schema.packageVersion)};\nexport const PRODUCT_FIELDS = ${JSON.stringify(names)};\nexport const REQUEST_FIELDS = ${JSON.stringify(requestFields)};\nexport const REQUEST_ENUMS = ${JSON.stringify(requestEnums)};\nexport const WORKER_MESSAGE_FIELDS = ${JSON.stringify(workerMessageFields)};\nconst VALIDATION_SCHEMA = ${JSON.stringify(validationSchema)};\n${runtimeValidatorSource()}`;
const dts = `${header}${objectDeclaration("ProductSet", schema.productSet)}\n\n${Object.entries(schema.enums).map(([name, values]) => enumDeclaration(name, values)).join("\n\n")}\n\n${Object.entries(schema.settings).map(([name, contract]) => objectDeclaration(name, contract)).join("\n\n")}\n\n${Object.entries(schema.definitions).map(([name, contract]) => objectDeclaration(name, contract)).join("\n\n")}\n\n${Object.entries(schema.preprocessDefinitions).map(([name, contract]) => objectDeclaration(name, contract)).join("\n\n")}\n\n${Object.entries(schema.taggedUnions).map(([name, contract]) => unionDeclaration(name, contract)).join("\n\n")}\n\n${Object.entries(schema.dtos).map(([name, contract]) => objectDeclaration(name, contract)).join("\n\n")}\n\n${objectDeclaration("WasmRequest", schema.request)}\n\n${objectDeclaration("PreprocessRequest", schema.preprocessRequest)}\n\n${updateRequestDeclaration()}\n\n${objectDeclaration("AdocWeaveWasmResponse", schema.response)}\n\n${unionDeclaration("WorkerRequest", schema.workerEnvelopes.requests)}\n\n${unionDeclaration("WorkerResponse", schema.workerEnvelopes.responses)}\n\n${objectDeclaration("AdocWeaveError", schema.workerEnvelopes.clientError)}\n\nexport declare const PROTOCOL_SCHEMA_VERSION: ${schema.schemaVersion};\nexport declare const WORKER_PROTOCOL_VERSION: ${schema.workerProtocolVersion};\nexport declare const PACKAGE_VERSION: ${JSON.stringify(schema.packageVersion)};\nexport declare const PRODUCT_FIELDS: readonly [${names.map(JSON.stringify).join(", ")}];\nexport declare const REQUEST_FIELDS: readonly [${requestFields.map(JSON.stringify).join(", ")}];\nexport declare const REQUEST_ENUMS: ${literalType(requestEnums)};\nexport declare const WORKER_MESSAGE_FIELDS: ${literalType(workerMessageFields)};\nexport declare function validateWorkerMessage(value: unknown, direction: "requests" | "responses"): value is WorkerRequest | WorkerResponse;\nexport declare function validateClientError(value: unknown): value is AdocWeaveError;\n`;
const rust = `${header}\npub const PROTOCOL_SCHEMA_VERSION: u16 = ${schema.schemaVersion};\npub const WORKER_PROTOCOL_VERSION: u16 = ${schema.workerProtocolVersion};\n\n#[derive(Clone, Copy, Debug, serde::Deserialize, serde::Serialize, Eq, PartialEq)]\n#[serde(rename_all = "camelCase", deny_unknown_fields)]\npub struct WasmProductSet {\n${rustFields.map((name) => `    pub ${name}: bool,`).join("\n")}\n}\n\nimpl Default for WasmProductSet {\n    fn default() -> Self {\n        let products = adocweave::ProductSet::browser_default();\n        Self {\n${rustFields.map((name) => `            ${name}: products.${name},`).join("\n")}\n        }\n    }\n}\n\nimpl From<WasmProductSet> for adocweave::ProductSet {\n    fn from(value: WasmProductSet) -> Self {\n        Self {\n${rustFields.map((name) => `            ${name}: value.${name},`).join("\n")}\n        }\n    }\n}\n`;
const preprocessRust = `${header}\n${generateRustPreprocessInputs(schema)}\n`;
const outputs = [
  [new URL("web-worker/protocol.generated.mjs", root), mjs],
  [new URL("web-worker/protocol.generated.d.mts", root), dts],
  [new URL("crates/adocweave-wasm/src/protocol_generated.rs", root), rust],
  [new URL("crates/adocweave-wasm/src/preprocess_wire_generated.rs", root), preprocessRust],
];
const check = process.argv.includes("--check");
let stale = false;
for (const [path, content] of outputs) {
  let actual = "";
  try { actual = readFileSync(path, "utf8"); } catch {}
  if (actual === content) continue;
  stale = true;
  if (!check) writeFileSync(path, content);
}
if (check && stale) throw new Error("generated protocol files are stale; run node tools/generate-protocol.mjs");

function validateSchema() {
  if (!Number.isInteger(schema.schemaVersion) || !Number.isInteger(schema.workerProtocolVersion)) {
    throw new Error("protocol versions must be integers");
  }
  if (schema.request.unknownFields !== "reject") throw new Error("request must reject unknown fields");
  const fields = schema.request.fields;
  if (!Array.isArray(fields) || new Set(fields.map(({ json }) => json)).size !== fields.length) {
    throw new Error("request fields must have unique names");
  }
  for (const field of fields) {
    if (!field.json || !field.type || (field.required !== true && !Object.hasOwn(field, "default"))) {
      throw new Error(`request field ${field.json ?? "<unnamed>"} must be required or have a default`);
    }
  }
  for (const [name, setting] of Object.entries(schema.settings)) {
    if (setting.unknownFields !== "reject") throw new Error(`${name} must reject unknown fields`);
    for (const field of setting.fields) {
      if (!Object.hasOwn(field, "default")) throw new Error(`${name}.${field.json} has no default`);
    }
  }
  validateTypeReferences();
  validateRuntimeBindings();
  validateRequestObjectCorpus();
  validateRequestUnionCorpus();
  validatePreprocessCorpus();
  validateOutputContracts();
  const covered = corpus.enumCases.map(({ enum: name }) => name).sort();
  const expected = [...schema.requestEnums].sort();
  if (JSON.stringify(covered) !== JSON.stringify(expected)) {
    throw new Error("protocol corpus does not cover every request enum exactly once");
  }
  for (const name of expected) {
    if (!Array.isArray(schema.enums[name]) || schema.enums[name].length === 0) {
      throw new Error(`request enum ${name} is missing`);
    }
  }
  if (corpus.oldVersion === schema.packageVersion) throw new Error("old-version corpus uses the current version");
}

function runtimeValidationSchema(value) {
  return JSON.parse(JSON.stringify(value, (name, item) =>
    name === "collection" ? undefined : item
  ));
}

function validateOutputContracts() {
  const visited = new Set();
  const visitType = (type) => {
    for (const reference of type.match(/[A-Z][A-Za-z0-9]*/g) ?? []) {
      if (reference === "ProductSet") {
        visitObject("ProductSet", schema.productSet);
      } else if (reference === "AdocWeaveWasmResponse") {
        visitObject(reference, schema.response);
      } else if (schema.taggedUnions[reference]) {
        visitUnion(reference, schema.taggedUnions[reference]);
      } else {
        const contract = schema.definitions[reference]
          ?? schema.dtos[reference] ?? schema.preprocessDefinitions[reference];
        if (contract) visitObject(reference, contract);
      }
    }
  };
  const visitObject = (name, contract) => {
    if (visited.has(name)) return;
    visited.add(name);
    for (const field of contract.fields) {
      if (Object.hasOwn(field, "default")) {
        throw new Error(`output field ${name}.${field.json} must be required`);
      }
      visitType(field.type);
    }
  };
  const visitUnion = (name, contract) => {
    if (visited.has(name)) return;
    visited.add(name);
    for (const fields of Object.values(contract.variants)) {
      for (const field of fields) {
        if (Object.hasOwn(field, "default")) {
          throw new Error(`output union field ${name}.${field.json} must be required`);
        }
        visitType(field.type);
      }
    }
  };
  visitObject("AdocWeaveWasmResponse", schema.response);
  visitObject("PreprocessResponse", schema.preprocessDefinitions.PreprocessResponse);
  visitObject("WasmError", schema.preprocessDefinitions.WasmError);
  visitObject("AdocWeaveError", schema.workerEnvelopes.clientError);
}

function validatePreprocessCorpus() {
  const covered = corpus.preprocessObjectCases.map(({ object }) => object).sort();
  const expected = [...schema.preprocessObjects].sort();
  if (JSON.stringify(covered) !== JSON.stringify(expected)) {
    throw new Error("protocol corpus does not cover every preprocess object exactly once");
  }
  for (const name of expected) {
    const contract = name === "PreprocessRequest"
      ? schema.preprocessRequest
      : schema.preprocessDefinitions[name];
    if (!contract || contract.unknownFields !== "reject") {
      throw new Error(`${name} must exist and reject unknown fields`);
    }
    for (const field of contract.fields) {
      if (field.required !== true && !Object.hasOwn(field, "default")) {
        throw new Error(`${name}.${field.json} must be required or declare a default`);
      }
    }
  }
  const reachable = reachableTypes(
    ["PreprocessRequest", "PreprocessResponse", "WasmError"],
    (name) => name === "PreprocessRequest"
      ? schema.preprocessRequest
      : schema.preprocessDefinitions[name],
  );
  const definitions = Object.keys(schema.preprocessDefinitions).sort();
  if (JSON.stringify([...reachable].filter((name) => name !== "PreprocessRequest").sort()) !== JSON.stringify(definitions)) {
    throw new Error("preprocess definitions must exactly match the reachable type set");
  }
}

function reachableTypes(roots, contractFor) {
  const reached = new Set();
  const pending = [...roots];
  while (pending.length > 0) {
    const name = pending.pop();
    if (reached.has(name)) continue;
    const contract = contractFor(name);
    if (!contract) continue;
    reached.add(name);
    for (const field of contract.fields) {
      for (const reference of field.type.match(/[A-Z][A-Za-z0-9]*/g) ?? []) {
        if (contractFor(reference) && !reached.has(reference)) pending.push(reference);
      }
    }
  }
  return reached;
}

function validateRequestUnionCorpus() {
  const covered = corpus.unionCases.map(({ union }) => union).sort();
  const expected = [...schema.requestUnions].sort();
  if (JSON.stringify(covered) !== JSON.stringify(expected)) {
    throw new Error("protocol corpus does not cover every request union exactly once");
  }
  for (const name of expected) {
    const contract = schema.taggedUnions[name];
    if (!contract) throw new Error(`undefined request union ${name}`);
    if (contract.unknownFields !== "reject") {
      throw new Error(`${name} must declare unknown-field rejection`);
    }
    const fixture = corpus.unionCases.find(({ union }) => union === name);
    const variants = Object.keys(contract.variants).sort();
    if (JSON.stringify(Object.keys(fixture.variants).sort()) !== JSON.stringify(variants)) {
      throw new Error(`${name} corpus must cover every variant`);
    }
  }
}

function validateRequestObjectCorpus() {
  const covered = corpus.objectCases.map(({ object }) => object).sort();
  const expected = [...schema.requestObjects].sort();
  if (JSON.stringify(covered) !== JSON.stringify(expected)) {
    throw new Error("protocol corpus does not cover every request object exactly once");
  }
  for (const name of expected) {
    const contract = name === "WasmRequest"
      ? schema.request
      : name === "ProductSet"
        ? schema.productSet
        : schema.settings[name] ?? schema.definitions[name];
    if (!contract) throw new Error(`undefined request object ${name}`);
    if (contract.unknownFields !== "reject") {
      throw new Error(`${name} must declare unknown-field rejection`);
    }
    for (const field of contract.fields) {
      if (field.required !== true && !Object.hasOwn(field, "default")) {
        throw new Error(`${name}.${field.json} must be required or declare a default`);
      }
    }
  }
}

function validateTypeReferences() {
  const declared = new Set([
    ...Object.keys(schema.enums),
    ...Object.keys(schema.settings),
    ...Object.keys(schema.definitions),
    ...Object.keys(schema.preprocessDefinitions),
    ...Object.keys(schema.taggedUnions),
    ...Object.keys(schema.dtos),
    "ProductSet",
    "WasmRequest",
    "AdocWeaveWasmResponse",
  ]);
  const builtins = new Set(["string", "number", "u32", "safeInteger", "boolean", "null", "unknown", "Record", "Required", "SharedArrayBuffer"]);
  const contracts = [
    schema.request,
    schema.response,
    schema.preprocessRequest,
    schema.productSet,
    ...Object.values(schema.settings),
    ...Object.values(schema.definitions),
    ...Object.values(schema.preprocessDefinitions),
    ...Object.values(schema.dtos),
    ...Object.values(schema.taggedUnions).flatMap((union) =>
      Object.values(union.variants).map((fields) => ({ fields })),
    ),
    ...[schema.workerEnvelopes.requests, schema.workerEnvelopes.responses].flatMap((union) =>
      Object.values(union.variants).map((fields) => ({ fields })),
    ),
    schema.workerEnvelopes.clientError,
  ];
  for (const contract of contracts) {
    for (const field of contract.fields) {
      const references = field.type.match(/[A-Za-z][A-Za-z0-9]*/g) ?? [];
      for (const reference of references) {
        if (!builtins.has(reference) && !declared.has(reference)) {
          throw new Error(`undefined protocol type ${reference} in field ${field.json}`);
        }
      }
    }
  }
}

function validateRuntimeBindings() {
  if (runtimeBindings.schemaVersion !== 1 || !Array.isArray(runtimeBindings.bindings)) {
    throw new Error("invalid protocol runtime binding fixture");
  }
  for (const { consumer, source, name } of runtimeBindings.bindings) {
    const contents = readFileSync(new URL(consumer, root), "utf8");
    const importPattern = new RegExp(
      `(?:import|export)\\s*\\{[^}]*\\b${escapeRegExp(name)}\\b[^}]*\\}\\s*from\\s*["']${escapeRegExp(source)}["']`,
    );
    if (!importPattern.test(contents)) {
      throw new Error(`${consumer} must bind ${name} from ${source}`);
    }
    const assignmentPattern = new RegExp(`(?:const|let|var)\\s+${escapeRegExp(name)}\\s*=`);
    if (assignmentPattern.test(contents)) {
      throw new Error(`${consumer} must not define ${name} by hand`);
    }
  }
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function literalType(value) {
  if (value === null) return "null";
  if (Array.isArray(value)) return `readonly [${value.map(literalType).join(", ")}]`;
  if (typeof value === "object") {
    const fields = Object.entries(value)
      .map(([key, item]) => `readonly ${JSON.stringify(key)}: ${literalType(item)}`)
      .join("; ");
    return `{ ${fields} }`;
  }
  return JSON.stringify(value);
}

function enumDeclaration(name, values) {
  return `export type ${name} = ${values.map(JSON.stringify).join(" | ")};`;
}

function objectDeclaration(name, contract) {
  return `export interface ${name} {\n${contract.fields.map(fieldDeclaration).join("\n")}\n}`;
}

function fieldDeclaration(field) {
  const optional = Object.hasOwn(field, "default") ? "?" : "";
  return `  ${field.json}${optional}: ${typescriptType(field.type)};`;
}

function unionDeclaration(name, contract) {
  const variants = Object.entries(contract.variants).map(([tag, fields]) => {
    const declarations = [{ json: contract.tag, type: JSON.stringify(tag), required: true }, ...fields];
    return `{ ${declarations.map((field) => `${field.json}${Object.hasOwn(field, "default") ? "?" : ""}: ${typescriptType(field.type)}`).join("; ")} }`;
  });
  return `export type ${name} =\n  | ${variants.join("\n  | ")};`;
}

function updateRequestDeclaration() {
  const exposed = new Set([
    "sourceId",
    "version",
    "source",
    "preprocess",
    "products",
    "renderInputs",
    "analysisOptions",
    "renderPolicy",
    "outputLimits",
  ]);
  return objectDeclaration("UpdateRequest", {
    fields: schema.request.fields.filter((field) => exposed.has(field.json)),
  });
}

function typescriptType(type) {
  return type.replace(/\bu32\b|\bsafeInteger\b/g, "number");
}

function runtimeValidatorSource() {
  return `export function validateWorkerMessage(value, direction) {
  const contract = VALIDATION_SCHEMA.workerEnvelopes[direction];
  return contract !== undefined && validateUnion(value, contract);
}
export function validateClientError(value) {
  return validateObject(value, VALIDATION_SCHEMA.workerEnvelopes.clientError);
}
function validateValue(value, type) {
  if (type === "string") return typeof value === "string";
  if (type === "number") return typeof value === "number" && Number.isFinite(value);
  if (type === "u32") return Number.isInteger(value) && value >= 0 && value <= 4294967295;
  if (type === "safeInteger") return Number.isSafeInteger(value) && value >= 0;
  if (type === "boolean") return typeof value === "boolean";
  if (type === "unknown") return true;
  if (type.endsWith(" | null")) return value === null || validateValue(value, type.slice(0, -7));
  if (type.endsWith("[]")) return Array.isArray(value) && value.every((item) => validateValue(item, type.slice(0, -2)));
  if (type.startsWith("Record<string, ") && type.endsWith(">")) {
    const itemType = type.slice(15, -1);
    return isObject(value) && Object.values(value).every((item) => validateValue(item, itemType));
  }
  if (type === "Required<ProductSet>" || type === "ProductSet") return validateObject(value, VALIDATION_SCHEMA.productSet);
  if (type === "SharedArrayBuffer") return typeof SharedArrayBuffer === "function" && value instanceof SharedArrayBuffer;
  if (VALIDATION_SCHEMA.enums[type]) return VALIDATION_SCHEMA.enums[type].includes(value);
  if (VALIDATION_SCHEMA.taggedUnions[type]) return validateUnion(value, VALIDATION_SCHEMA.taggedUnions[type]);
  const contract = type === "WasmRequest" ? VALIDATION_SCHEMA.request
    : type === "PreprocessRequest" ? VALIDATION_SCHEMA.preprocessRequest
    : type === "AdocWeaveWasmResponse" ? VALIDATION_SCHEMA.response
    : VALIDATION_SCHEMA.settings[type] ?? VALIDATION_SCHEMA.definitions[type]
      ?? VALIDATION_SCHEMA.preprocessDefinitions[type] ?? VALIDATION_SCHEMA.dtos[type];
  return contract !== undefined && validateObject(value, contract);
}
function validateObject(value, contract) {
  if (!isObject(value)) return false;
  const fields = new Map(contract.fields.map((field) => [field.json, field]));
  if (Object.keys(value).some((name) => !fields.has(name))) return false;
  return contract.fields.every((field) => {
    if (!Object.hasOwn(value, field.json)) return Object.hasOwn(field, "default");
    return validateValue(value[field.json], field.type);
  });
}
function validateUnion(value, contract) {
  if (!isObject(value) || typeof value[contract.tag] !== "string") return false;
  const fields = contract.variants[value[contract.tag]];
  if (!fields) return false;
  return validateObject(value, { fields: [{ json: contract.tag, type: "string" }, ...fields] });
}
function isObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
`;
}
